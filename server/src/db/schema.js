/**
 * 全部表定义（唯一事实来源）。
 *
 * 设计说明（与规划书 4.2 的差异，均为跨方言兼容的工程取舍）：
 *  1. json 字段用 text 存 JSON 字符串：MySQL 的 json 类型读出来是已解析对象、
 *     SQLite 读出来是字符串，同一份业务代码会在两个方言下出现两种行为。
 *  2. decimal 字段用字符串存 "12.34"：全站金额以整数分运算（core/money.js），
 *     SQLite 的 NUMERIC 会把 decimal 退化成浮点，规划书明确禁止金额用浮点。
 *  3. datetime 一律由应用层写入 "YYYY-MM-DD HH:mm:ss"，不依赖 NOW()/ON UPDATE，
 *     这样 cron 补算、跨库迁数据的行为都一致。
 */

